  const { schemaVersion, ...decisions } = decisionData;
  files.set('mcp/expressivecss/component-guides.json', json({ schemaVersion: 1, generatedBy, frameworkVersion, guides: [...guides.keys()].sort().map((file) => ({ file, content: guides.get(file) })) }));
