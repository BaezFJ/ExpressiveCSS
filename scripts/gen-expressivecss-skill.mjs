function rebaseHeadings(markdown, offset) {
  return markdown.split(/(```[\s\S]*?```)/u).map((part, index) => index % 2 ? part
    : part.replace(/^(#{1,6}) /gmu, (_, hashes) => `${'#'.repeat(hashes.length + offset)} `)).join('');
}

