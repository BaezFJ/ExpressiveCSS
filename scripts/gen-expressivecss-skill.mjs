import { mkdir, readFile, readdir, unlink, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { transform } from 'esbuild';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const COMPONENTS_DIR = resolve(ROOT, 'skills/expressivecss/components');
const GENERATED_MARKER = '<!-- Generated by scripts/gen-expressivecss-skill.mjs. Do not edit. -->';
const RESOLVER_MARKER = '// Generated from scripts/lib/resolve-expressivecss-version.mjs. Do not edit.\n';
const RESOLVER_SOURCE = resolve(ROOT, 'scripts/lib/resolve-expressivecss-version.mjs');
const RESOLVER_DESTINATIONS = [
  resolve(ROOT, 'skills/expressivecss/scripts/resolve-version.mjs'),
  resolve(ROOT, 'mcp/expressivecss/scripts/resolve-version.mjs'),
];
const DECISIONS_SOURCE = resolve(ROOT, 'docs/src/data/component-decisions.json');
const DECISIONS_DESTINATION = resolve(ROOT, 'skills/expressivecss/references/component-decisions.md');
const CONTRACT_DESTINATIONS = [
  resolve(ROOT, 'skills/expressivecss/references/contract.json'),
  resolve(ROOT, 'mcp/expressivecss/contract.json'),
];
const CONTRACT_SOURCES = [
  'llm.md',
  'semantics.json',
  'docs/src/data/nav.ts',
  'docs/src/data/component-decisions.json',
  'package.json',
  'CHANGELOG.md',
];
const decisionText = await readFile(DECISIONS_SOURCE, 'utf8');
const decisionData = JSON.parse(decisionText);

async function contractProvenance() {
  const inputs = await Promise.all(CONTRACT_SOURCES.map(async (source) => [
    source,
    await readFile(resolve(ROOT, source), 'utf8'),
  ]));
  const hash = createHash('sha256');
  for (const [source, content] of inputs) hash.update(`${source}\0${content}\0`);
  const packageText = inputs.find(([source]) => source === 'package.json')[1];
  const changelog = inputs.find(([source]) => source === 'CHANGELOG.md')[1];
  const version = JSON.parse(packageText).version;
  const releaseTags = changelog.split(/\r?\n/u)
    .flatMap((line) => {
      const match = /^\[([^\]]+)\]:\s+\S+\.\.\.v([^\s]+)$/u.exec(line);
      return match && match[1] === match[2] ? [`v${match[1]}`] : [];
    })
    .sort();
  return { version, hash: hash.digest('hex'), releaseTags };
}

async function syncResolver(checkOnly) {
  const expected = `${RESOLVER_MARKER}${await readFile(RESOLVER_SOURCE, 'utf8')}`;
  const stale = [];
  for (const destination of RESOLVER_DESTINATIONS) {
    if (checkOnly) {
      const current = await readFile(destination, 'utf8').catch(() => '');
      if (current !== expected) stale.push(destination);
    } else {
      await mkdir(dirname(destination), { recursive: true });
      await writeFile(destination, expected);
    }
  }
  if (stale.length) {
    throw new Error(`Generated version resolver is stale: ${stale.join(', ')}`);
  }
}

function renderDecisionIndex(data) {
  const cell = (value) => String(value).replaceAll('|', '\\|').replaceAll('\n', ' ');
  const rows = data.components.map((component) => {
    const alternatives = component.alternatives.length
      ? component.alternatives.map((slug) => `[${slug}](../components/${slug}.md)`).join(', ')
      : 'Compare plausible candidates';
    const adaptive = component.adaptive
      .map((item) => {
        const target = item.component ? ` ${item.component}` : '';
        return `${item.window} ${item.basis}: ${item.kind}${target}. ${item.reason}`;
      })
      .join('; ') || 'Read full guidance';
    const materialGuidance = component.materialGuidance.status === 'material'
      ? `[Material guidance](${component.materialGuidance.href})`
      : 'Framework extra';
    return `| [${cell(component.title)}](${component.guide}) | ${cell(component.useWhen.join('; '))} | ${cell(component.avoidWhen.join('; '))} | ${cell(alternatives)} | ${cell(adaptive)} | ${cell(component.runtime)} | ${materialGuidance} |`;
  });
  return `${GENERATED_MARKER}\n\n# ExpressiveCSS component decisions\n\nUse this index to narrow candidates by user job, interaction model, and window class. Then read every plausible candidate guide. This index does not replace component syntax, semantics, or target-version documentation.\n\n| Component | Use when | Avoid when | Alternatives | Adaptive | Runtime | Material guidance |\n| --- | --- | --- | --- | --- | --- | --- |\n${rows.join('\n')}\n`;
}

async function syncDecisionIndex(checkOnly) {
  const expected = renderDecisionIndex(decisionData);
  if (checkOnly) {
    const current = await readFile(DECISIONS_DESTINATION, 'utf8').catch(() => '');
    if (current !== expected) throw new Error('Generated component decision index is stale.');
  } else {
    await mkdir(dirname(DECISIONS_DESTINATION), { recursive: true });
    await writeFile(DECISIONS_DESTINATION, expected);
  }
}

async function contractManifest() {
  const [provenance, skillText] = await Promise.all([
    contractProvenance(),
    readFile(resolve(ROOT, 'skills/expressivecss/SKILL.md'), 'utf8'),
  ]);
  const skillVersion = /^\s{2}version:\s*"?([^"\n]+)"?$/mu.exec(skillText)?.[1];
  if (!skillVersion) throw new Error('The ExpressiveCSS skill workflow version is missing.');
  const matchingTag = provenance.releaseTags.includes(`v${provenance.version}`)
    ? `v${provenance.version}`
    : null;
  return {
    schemaVersion: 1,
    generatedBy: 'scripts/gen-expressivecss-skill.mjs',
    frameworkVersion: provenance.version,
    skillVersion,
    matchingTag,
    releaseTags: provenance.releaseTags,
    sources: CONTRACT_SOURCES,
    sourceHash: provenance.hash,
  };
}

async function syncContractManifest(checkOnly) {
  const expected = `${JSON.stringify(await contractManifest(), null, 2)}\n`;
  const stale = [];
  for (const destination of CONTRACT_DESTINATIONS) {
    if (checkOnly) {
      const current = await readFile(destination, 'utf8').catch(() => '');
      if (current !== expected) stale.push(destination);
    } else {
      await mkdir(dirname(destination), { recursive: true });
      await writeFile(destination, expected);
    }
  }
  if (stale.length) throw new Error(`Generated contract manifest is stale: ${stale.join(', ')}`);
}

async function loadCatalogue() {
  const source = await readFile(resolve(ROOT, 'docs/src/data/nav.ts'), 'utf8');
  // Node 20 cannot import TypeScript directly; use the existing build tool in memory.
  const { code } = await transform(source, {
    format: 'esm',
    loader: 'ts',
    sourcefile: 'nav.ts',
    target: 'es2020',
  });
  return import(`data:text/javascript;base64,${Buffer.from(code).toString('base64')}`);
}

const { NAV, PAGES } = await loadCatalogue();

const COMPONENT_GROUPS = new Set(['Structure', 'Components', 'Forms']);
const cataloguePages = NAV
  .filter((group) => COMPONENT_GROUPS.has(group.label))
  .flatMap((group) => group.pages.map((page) => page.id));
const decisionComponentsByPage = new Map(
  decisionData.components.map((component) => [component.guideSource.pageId, component]),
);
const components = cataloguePages.map((pageId) => decisionComponentsByPage.get(pageId)).map((component) => ({
  slug: component.slug,
  title: component.title,
  page: component.guideSource.pageId,
  heading: component.guideSource.heading,
  level: component.guideSource.headingLevel,
  semantics: component.guideSource.semantics,
  excludeRules: component.guideSource.excludeRules ?? [],
  syntaxLanguage: component.guideSource.syntaxLanguage,
}));

async function validateComponentInventory() {
  const mappedPages = components.map((component) => component.page);
  if (JSON.stringify(mappedPages) !== JSON.stringify(cataloguePages)) {
    throw new Error(
      'The skill component map must match the Structure, Components, and Forms documentation catalogue in order.',
    );
  }

}

function sectionFor(markdown, title, level = 2) {
  const heading = `${'#'.repeat(level)} ${title}`;
  const lines = markdown.split('\n');
  const starts = lines.flatMap((line, index) => line === heading ? [index] : []);
  if (starts.length !== 1) {
    throw new Error(`Expected one ${JSON.stringify(heading)} heading, found ${starts.length}`);
  }
  const start = starts[0] + 1;
  let end = lines.length;
  for (let index = start; index < lines.length; index += 1) {
    const match = /^(#{1,6}) /.exec(lines[index]);
    if (match && match[1].length <= level) {
      end = index;
      break;
    }
  }
  return lines.slice(start, end).join('\n').trim();
}

function contractSummary(section) {
  const beforeExample = section.split(/\n```/u, 1)[0];
  return beforeExample
    .split(/\n\s*\n/u)
    .map((paragraph) => paragraph.trim())
    .filter((paragraph) => paragraph && !paragraph.startsWith('#') && !paragraph.startsWith('|'))
    .map((paragraph) => paragraph
      .replace(/\[([^\]]+)\]\((?!https?:\/\/)[^)]+\)/gu, '$1')
      .replaceAll('\n', ' '))
    .filter((paragraph) => /[.!?:]$/u.test(paragraph) || paragraph.includes('`'))
    .slice(0, 3)
    .join('\n\n');
}

function firstCodeExample(section, slug, language) {
  const match = new RegExp(`\`\`\`${language}\\n([\\s\\S]*?)\\n\`\`\``, 'u').exec(section);
  if (!match) throw new Error(`No ${language} example found for ${slug}`);
  return match[1].trimEnd();
}

function semanticRules(rows, names, excluded = []) {
  const excludedIds = new Set(excluded);
  const rules = names.flatMap((name) => {
    const row = rows[name];
    if (!row) throw new Error(`Unknown semantics row ${name}`);
    return row.rules.filter((rule) => !excludedIds.has(rule.id));
  });
  const ids = rules.map((rule) => rule.id);
  if (new Set(ids).size !== ids.length) {
    throw new Error(`Duplicate semantics rule ID in generated guide: ${ids.join(', ')}`);
  }
  return rules;
}

function sourcePagePath(page) {
  const routeSlug = page.route.replace(/^\//u, '').replace(/\.html$/u, '');
  return `https://github.com/BaezFJ/ExpressiveCSS/blob/master/docs/src/pages/${routeSlug}.astro`;
}

function renderGuide(component, page, section, rules, provenance) {
  const title = component.title ?? page.title ?? page.label;
  const officialMarkdown = `https://www.expressivecss.com${page.route}.md`;
  const syntaxLanguage = component.syntaxLanguage ?? 'html';
  const example = firstCodeExample(section, component.slug, syntaxLanguage);
  const guideChecks = [];
  if (/<nav(?:\s|>)/u.test(example)) {
    guideChecks.push('Label every <nav> landmark with aria-label or aria-labelledby.');
  }
  const ruleLines = rules.length
    ? rules.map((rule) => `- \`${rule.id}\`: ${rule.message}`).join('\n')
    : 'No component-specific `semantics.json` rules apply to this guide.';
  const guideCheckLines = guideChecks.map((message) => `- ${message}`);
  guideCheckLines.push(
    '- Read the full target-version component documentation before using variants, options, methods, or events not shown here.',
    '- The target version\'s documentation and source override this generated summary if they disagree.',
  );
  const links = [
    `[Component documentation](${officialMarkdown})`,
    `[Repository source](${sourcePagePath(page)})`,
  ];
  if (provenance.matchingTag) {
    links.push(`[Matching tag](https://github.com/BaezFJ/ExpressiveCSS/tree/${provenance.matchingTag})`);
  }
  const renderedSources = CONTRACT_SOURCES.map((source) => `\`${source}\``).join(', ');

  return `${GENERATED_MARKER}\n\n### ${title}\n${page.description}\n\nComponent ID: \`${component.slug}\`\n\n${links.join(' · ')}\n\nContract: ExpressiveCSS ${provenance.version}\n\nSources: ${renderedSources}\n\nContract SHA-256: \`${provenance.hash}\`\n\n#### Contract\n\n${contractSummary(section)}\n\n#### Syntax\n\n\`\`\`${syntaxLanguage}\n${example}\n\`\`\`\n\n#### Rules\n\nThe following are end-state semantic invariants. The rule IDs come directly from \`semantics.json\`; keep them when creating component review criterion instances. Author static requirements; verify component-generated state instead of pre-authoring values the runtime owns.\n\n${ruleLines}\n\n#### Guide checks\n\n${guideCheckLines.join('\n')}\n`;
}

async function generatedGuides() {
  const [llm, semanticsText, provenance] = await Promise.all([
    readFile(resolve(ROOT, 'llm.md'), 'utf8'),
    readFile(resolve(ROOT, 'semantics.json'), 'utf8'),
    contractProvenance(),
  ]);
  provenance.matchingTag = provenance.releaseTags.includes(`v${provenance.version}`)
    ? `v${provenance.version}`
    : null;
  const rows = JSON.parse(semanticsText).rows;
  const pages = new Map(PAGES.map((page) => [page.id, page]));
  return new Map(components.map((component) => {
    const page = pages.get(component.page);
    if (!page) throw new Error(`Unknown docs page ${component.page}`);
    const section = sectionFor(llm, component.heading, component.level ?? 2);
    const rules = semanticRules(rows, component.semantics, component.excludeRules);
    return [`${component.slug}.md`, renderGuide(component, page, section, rules, provenance)];
  }));
}

async function check(guides) {
  const errors = [];
  let names = [];
  try {
    names = (await readdir(COMPONENTS_DIR)).filter((name) => name.endsWith('.md')).sort();
  } catch {
    errors.push('component guide directory is missing');
  }
  const expectedNames = [...guides.keys()].sort();
  if (JSON.stringify(names) !== JSON.stringify(expectedNames)) {
    errors.push(`component guide inventory differs: expected ${expectedNames.join(', ')}`);
  }
  for (const [name, expected] of guides) {
    try {
      const actual = await readFile(resolve(COMPONENTS_DIR, name), 'utf8');
      if (actual !== expected) errors.push(`${name} is stale`);
    } catch {
      errors.push(`${name} is missing`);
    }
  }
  if (errors.length) {
    for (const error of errors) console.error(error);
    process.exitCode = 1;
  } else {
    console.log(`${guides.size} ExpressiveCSS component guides are current.`);
  }
}

async function write(guides) {
  await mkdir(COMPONENTS_DIR, { recursive: true });
  const expected = new Set(guides.keys());
  for (const name of await readdir(COMPONENTS_DIR)) {
    if (!name.endsWith('.md') || expected.has(name)) continue;
    const path = resolve(COMPONENTS_DIR, name);
    const content = await readFile(path, 'utf8');
    if (content.startsWith(GENERATED_MARKER)) await unlink(path);
  }
  await Promise.all([...guides].map(([name, content]) => writeFile(resolve(COMPONENTS_DIR, name), content)));
  console.log(`Wrote ${guides.size} ExpressiveCSS component guides.`);
}

await validateComponentInventory();
const guides = await generatedGuides();
const checkOnly = process.argv.includes('--check');
await syncResolver(checkOnly);
await syncDecisionIndex(checkOnly);
await syncContractManifest(checkOnly);
if (checkOnly) await check(guides);
else await write(guides);
