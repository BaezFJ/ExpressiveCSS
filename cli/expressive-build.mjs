#!/usr/bin/env node
import { createHash, randomUUID } from 'node:crypto';
import { existsSync, lstatSync, mkdirSync, readdirSync, readFileSync, realpathSync, renameSync, rmSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { basename, dirname, extname, join, relative, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseArgs } from 'node:util';
import { collectAPIReferences, collectUsage, selectedStyles } from './usage.mjs';

const framework = fileURLToPath(new URL('..', import.meta.url));
const usage = `Usage: expressive-build [files or directories...] [options]

  --entry <file>      Bundle a browser JS/TS entry into js/app.js and imported CSS into css/app.css.
  --out-dir <path>    Write assets here (default: public/expressive).
  --include <name>    Keep a literal class, public JS API's styles, or components/<partial>.
                      Repeat for names supplied by a CMS or constructed at runtime.
  --check             Compare the expected files without writing; exit 1 if stale.
  --help              Show this help.

Scans the current directory by default. CSS is written to css/expressive.css,
with licensed fonts in fonts/. JavaScript bundling requires esbuild as a dev dependency.`;

const options = {
  entry: { type: 'string' }, 'out-dir': { type: 'string', default: 'public/expressive' },
  include: { type: 'string', multiple: true, default: [] }, check: { type: 'boolean' },
  help: { type: 'boolean', short: 'h' },
};
const extensions = new Set('.html .htm .js .mjs .cjs .ts .mts .cts .jsx .tsx .vue .svelte .astro .mdx .php .erb .ejs .hbs .twig .njk .liquid .css .scss'.split(' '));
const ignored = new Set(['node_modules', 'vendor', 'dist', 'build', '_site', 'coverage']);
const generatedBanner = '/*! Generated by expressive-build */';
const bundleJS = 'js/app.js';
const bundleCSS = 'css/app.css';

function isSourceFile(path) {
  return extensions.has(extname(path).toLowerCase()) && !/\.(?:min\.js|min\.css|d\.[cm]?ts)$/i.test(path);
}

function sourcePaths(path, out) {
  const stat = lstatSync(path);
  if (stat.isDirectory()) {
    return readdirSync(path).filter(name => !name.startsWith('.') && !ignored.has(name))
      .map(name => join(path, name)).filter(child => child !== out).flatMap(child => sourcePaths(child, out));
  }
  return stat.isFile() && isSourceFile(path) ? [path] : [];
}

function scanFiles(inputs, out) {
  const paths = inputs.map(input => resolve(input));
  const overlap = paths.find(path => path === out || path.startsWith(out + sep));
  if (overlap) throw new Error(`Input falls inside the output directory: ${overlap}`);
  const files = new Set(paths.flatMap(path => sourcePaths(path, out)).map(path => realpathSync(path)));
  if (!files.size) throw new Error('No application source files found. Pass a template, source directory or JS entry.');
  return files;
}

function stylesheetClasses(tokens, source) {
  for (const [, name] of source.matchAll(/\.([\w-]+(?:\\:[\w-]+)*)/g)) tokens.add(name.replaceAll('\\:', ':'));
}

function scan(files, bundledInputs) {
  const tokens = new Set();
  for (const file of files) {
    const source = readFileSync(file, 'utf8');
    collectUsage(tokens, source);
    if (!bundledInputs?.has(file)) {
      // With --entry the bundle determines live module imports. Templates and
      // separate scripts can still use the browser global.
      const scanImports = !bundledInputs || !/\.[cm]?[jt]sx?$/i.test(file);
      collectAPIReferences(tokens, source, scanImports);
    }
    if (/\.s?css$/.test(file)) stylesheetClasses(tokens, source);
  }
  return tokens;
}

function consumerBundler(entry) {
  const require = createRequire(entry);
  let path;
  try {
    path = require.resolve('esbuild', { paths: [dirname(entry), framework] });
  } catch (error) {
    if (error.code === 'MODULE_NOT_FOUND') throw new Error('Install the browser bundler with npm install -D esbuild.');
    throw error;
  }
  const { build } = require(path);
  if (typeof build !== 'function') throw new Error('The installed esbuild must provide build() for --entry. Run npm install -D esbuild.');
  return build;
}

async function bundle(entry, out) {
  const build = consumerBundler(entry);
  const inputs = new Set();
  const { outputFiles, metafile } = await build({
    entryPoints: [entry], outdir: out, entryNames: '[ext]/app', bundle: true, format: 'esm', target: 'es2020', minify: true,
    write: false, metafile: true, legalComments: 'inline', banner: { js: generatedBanner, css: generatedBanner }, logLevel: 'silent',
    loader: Object.fromEntries('.svg .png .jpg .jpeg .gif .webp .avif .ico .woff .woff2 .ttf .otf .eot'.split(' ').map(ext => [ext, 'dataurl'])),
    plugins: [{ name: 'selected-styles', setup(builder) {
      // File paths here exclude URL query strings and virtual modules.
      builder.onLoad({ filter: /.*/, namespace: 'file' }, ({ path }) => { inputs.add(realpathSync(path)); });
      builder.onResolve({ filter: /^\// }, args => {
        if (args.kind === 'url-token' || args.kind === 'import-rule') return { path: args.path, external: true };
      });
      // The matching selective CSS is emitted separately beside the fonts.
      builder.onResolve({ filter: /^@expressivecss\/expressive\/css(?:\/min)?$/ },
        () => ({ path: 'expressive.css', namespace: 'selective', sideEffects: false }));
      builder.onLoad({ filter: /.*/, namespace: 'selective' }, () => ({ contents: '', loader: 'empty' }));
    } }],
  });
  const files = new Map(outputFiles.map(file => [relative(out, file.path).split(sep).join('/'), Buffer.from(file.contents)]));
  if (!files.has(bundleJS)) throw new Error('--entry must be a browser JavaScript or TypeScript file.');
  const modules = new Set();
  const localJS = join(framework, 'dist/js') + sep;
  for (const output of Object.values(metafile.outputs)) {
    for (const [input, { bytesInOutput }] of Object.entries(output.inputs)) {
      if (bytesInOutput && (resolve(input).startsWith(localJS) || input.includes('node_modules/@expressivecss/expressive/dist/js/'))) {
        modules.add(basename(input));
      }
    }
  }
  return { files, inputs, modules };
}

function readExisting(path) {
  try { return readFileSync(path); }
  catch (error) { if (error.code !== 'ENOENT') throw error; }
}

function replace(path, content) {
  mkdirSync(dirname(path), { recursive: true });
  const temp = `${path}.${randomUUID()}.tmp`;
  try {
    writeFileSync(temp, content, { flag: 'wx' });
    renameSync(temp, path);
  } finally { rmSync(temp, { force: true }); }
}

function outputs(css, bundledFiles) {
  const files = new Map([
    ...bundledFiles,
    ['css/expressive.css', Buffer.from(css)],
    ['LICENSE-ExpressiveCSS', readFileSync(join(framework, 'LICENSE'))],
  ]);
  const fonts = join(framework, 'dist/fonts');
  for (const name of readdirSync(fonts).sort()) files.set(`fonts/${name}`, readFileSync(join(fonts, name)));
  return files;
}

function differences(out, files, inputs) {
  const changes = new Map();
  for (const name of new Set([...files.keys(), bundleJS, bundleCSS])) {
    const path = join(out, name);
    const previous = readExisting(path);
    const content = files.get(name);
    if (content === undefined && previous?.toString('utf8', 0, generatedBanner.length) !== generatedBanner) continue;
    if (previous && inputs.has(realpathSync(path))) throw new Error(`Output would overwrite an input file: ${path}`);
    if (content === undefined || !previous?.equals(content)) changes.set(path, content ?? null);
  }
  return changes;
}

function loadStyles() {
  const path = join(framework, 'dist/cli/styles.json');
  if (!existsSync(path)) throw new Error('Missing packaged style index. In a framework checkout, run npm run build first.');
  const index = JSON.parse(readFileSync(path, 'utf8'));
  const sheet = readFileSync(join(framework, 'dist/css/expressive.min.css'), 'utf8').replace(/^\uFEFF/, '');
  if (index.sha256 !== createHash('sha256').update(sheet).digest('hex')) {
    throw new Error('The stylesheet and usage index differ. Rebuild or reinstall ExpressiveCSS.');
  }
  return { index, sheet };
}

async function assets({ entry, include }, files, out) {
  const { index, sheet } = loadStyles();
  const bundled = entry ? await bundle(resolve(entry), out) : undefined;
  const tokens = scan(files, bundled?.inputs);
  if (bundled) {
    const js = bundled.files.get(bundleJS).toString();
    collectUsage(tokens, js);
    collectAPIReferences(tokens, js);
    const fullBundle = ['expressive.cjs', 'expressive.js', 'expressive.min.js'].some(name => bundled.modules.has(name));
    for (const [name, api] of Object.entries(index.apis)) {
      if (fullBundle || bundled.modules.has(api.chunk)) tokens.add(`api:${name}`);
    }
    const appCSS = bundled.files.get(bundleCSS);
    if (appCSS) stylesheetClasses(tokens, appCSS.toString());
  }
  const { css, names } = selectedStyles(index, sheet, tokens, include);
  console.log(`Scanned ${files.size} source files. Components: ${names.join(', ')}.`);
  return { output: outputs(css, bundled?.files ?? []), inputs: new Set([...files, ...(bundled?.inputs ?? [])]) };
}

function sync(out, changes, check) {
  if (!changes.size) return console.log(`Up to date: ${relative('.', out)}`);
  if (check) {
    const stale = Array.from(changes.keys(), path => relative(out, path));
    throw new Error(`Stale output in ${relative('.', out)}: ${stale.join(', ')}. Run expressive-build without --check.`);
  }
  changes.forEach((content, path) => {
    if (content === null) rmSync(path, { force: true });
    else replace(path, content);
  });
  console.log(`Built: ${relative('.', out)}`);
}

async function main() {
  const { values, positionals } = parseArgs({ options, allowPositionals: true });
  if (values.help) return console.log(usage);
  const out = resolve(values['out-dir']);
  const inputs = positionals.length ? positionals : ['.'];
  if (values.entry) inputs.push(values.entry);
  const files = scanFiles(inputs, out);
  const { output, inputs: sourceFiles } = await assets(values, files, out);
  sync(out, differences(out, output, sourceFiles), values.check);
}

main().catch(error => {
  console.error(`expressive-build: ${error.message}`);
  process.exitCode = 1;
});
