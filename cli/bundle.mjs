import { readFileSync, realpathSync } from 'node:fs';
import { createRequire } from 'node:module';
import { basename, dirname, extname, join, relative, resolve, sep } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { getBindingIdentifiers, isFunction, isScope, traverse } from '@babel/types';
import { memberName, parseScript, scriptFile, stringValue } from './javascript.mjs';

export const generatedBanner = '/*! Generated by expressive-build */';
export const bundleJS = 'js/app.js';
export const bundleCSS = 'css/app.css';
export const assetManifest = 'assets/expressive-build.json';
const assetNamespace = 'expressive-asset';

function consumerBundler(entry, framework) {
  const require = createRequire(entry);
  let path;
  try {
    path = require.resolve('esbuild', { paths: [dirname(entry), framework] });
  } catch (error) {
    if (error.code === 'MODULE_NOT_FOUND') throw new Error('Install the browser bundler with npm install -D esbuild.');
    throw error;
  }
  const { build } = require(path);
  if (typeof build !== 'function') throw new Error('The installed esbuild must provide build() for --entry. Run npm install -D esbuild.');
  return build;
}

function localURLScopes(tree) {
  const scopes = new Set();
  traverse(tree, (node, ancestors) => {
    const params = isFunction(node) ? node.params : (node.type === 'CatchClause' ? [node.param] : []);
    if (params.some(param => param && getBindingIdentifiers(param).URL)) scopes.add(node);
    if (node.id?.name === 'URL' && ['ClassExpression', 'FunctionExpression'].includes(node.type)) scopes.add(node);
    const declaresURL = node.type === 'VariableDeclaration' && getBindingIdentifiers(node).URL
      || node.type === 'ImportDeclaration' && node.importKind !== 'type'
        && node.specifiers.some(spec => spec.importKind !== 'type' && spec.local.name === 'URL')
      || ['ClassDeclaration', 'FunctionDeclaration', 'TSEnumDeclaration'].includes(node.type) && node.id?.name === 'URL';
    if (!declaresURL) return;
    const scope = ancestors.findLast(({ node: parent }, index) => node.kind === 'var'
      ? isFunction(parent) || parent.type === 'Program' : isScope(parent, ancestors[index - 1]?.node));
    if (scope) scopes.add(scope.node);
  });
  return scopes;
}

// Give esbuild a file import for each static module-relative URL. Its file loader
// picks the output URL relative to js/app.js and follows tree shaking.
function importURLAssets(source, path) {
  if (!source.includes('URL') || !source.includes('meta')) return;
  const tree = parseScript(source, path);
  const scopes = localURLScopes(tree);
  const imports = new Map();
  const edits = [];
  let prefix = '__expressiveAsset';
  while (source.includes(prefix)) prefix += '_';
  traverse(tree, (node, ancestors) => {
    if (node.type !== 'NewExpression' || node.callee.name !== 'URL' || ancestors.some(({ node }) => scopes.has(node))) return;
    const [argument, base] = node.arguments;
    if (memberName(base) !== 'url' || base.object.type !== 'MetaProperty' || base.object.meta.name !== 'import') return;
    const literal = stringValue(argument);
    if (!literal || /^(?:[a-z][a-z\d+.-]*:|[/?#\\])/i.test(literal)) return;
    const url = new URL(literal, pathToFileURL(path));
    const suffix = url.search + url.hash;
    url.search = url.hash = '';
    if (!imports.has(url.href)) imports.set(url.href, prefix + imports.size);
    const value = imports.get(url.href) + (suffix ? ` + ${JSON.stringify(suffix)}` : '');
    edits.push({ start: argument.start, end: argument.end, value });
  });
  if (!edits.length) return;
  const parts = [];
  let offset = 0;
  for (const { start, end, value } of edits.sort((a, b) => a.start - b.start)) {
    parts.push(source.slice(offset, start), value);
    offset = end;
  }
  parts.push(source.slice(offset), '\n');
  for (const [url, name] of imports) parts.push(`import ${name} from ${JSON.stringify(assetNamespace + ':' + url)};\n`);
  return parts.join('');
}

export async function bundle(entry, out, framework) {
  const build = consumerBundler(entry, framework);
  const inputPaths = new Map();
  const { outputFiles, metafile } = await build({
    entryPoints: [entry], outdir: out, entryNames: '[ext]/app', assetNames: 'assets/expressive-[hash]',
    bundle: true, format: 'esm', target: 'es2020', minify: true, write: false, metafile: true,
    legalComments: 'inline', banner: { js: generatedBanner, css: generatedBanner }, logLevel: 'silent',
    loader: Object.fromEntries('.svg .png .jpg .jpeg .gif .webp .avif .ico .woff .woff2 .ttf .otf .eot'.split(' ').map(ext => [ext, 'dataurl'])),
    plugins: [{ name: 'selected-styles', setup(builder) {
      builder.onLoad({ filter: /.*/, namespace: 'file' }, ({ path, suffix }) => {
        inputPaths.set(path + suffix, realpathSync(path));
        if (!scriptFile.test(path)) return;
        const contents = importURLAssets(readFileSync(path, 'utf8'), path);
        if (contents !== undefined) {
          const loader = extname(path).toLowerCase().slice(1).replace(/^[cm]/, '');
          return { contents, loader, resolveDir: dirname(path) };
        }
      });
      builder.onResolve({ filter: /^expressive-asset:file:/ }, ({ path }) => ({
        path: fileURLToPath(path.slice(assetNamespace.length + 1)), namespace: assetNamespace,
      }));
      builder.onLoad({ filter: /.*/, namespace: assetNamespace }, ({ path }) => {
        inputPaths.set(path, realpathSync(path));
        return { contents: readFileSync(path), loader: 'file' };
      });
      builder.onResolve({ filter: /^\// }, args => {
        if (args.kind === 'url-token' || args.kind === 'import-rule') return { path: args.path, external: true };
      });
      // The matching selective CSS is emitted separately beside the fonts.
      builder.onResolve({ filter: /^@expressivecss\/expressive\/css(?:\/min)?$/ },
        () => ({ path: 'expressive.css', namespace: 'selective', sideEffects: false }));
      builder.onLoad({ filter: /.*/, namespace: 'selective' }, () => ({ contents: '', loader: 'empty' }));
    } }],
  });
  const files = new Map(outputFiles.map(file => [relative(out, file.path).split(sep).join('/'), Buffer.from(file.contents)]));
  if (!files.has(bundleJS)) throw new Error('--entry must be a browser JavaScript or TypeScript file.');
  const assets = [...files.keys()].filter(name => name.startsWith('assets/')).sort();
  if (assets.length) files.set(assetManifest, Buffer.from(JSON.stringify({ generatedBy: 'expressive-build', assets }) + '\n'));
  const modules = new Set();
  const sources = new Set();
  const localJS = join(framework, 'dist/js') + sep;
  for (const output of Object.values(metafile.outputs)) {
    for (const [input, { bytesInOutput }] of Object.entries(output.inputs)) {
      const path = inputPaths.get(resolve(input));
      if (!bytesInOutput || !path || !scriptFile.test(path)) continue;
      if (path.startsWith(localJS) || input.includes('node_modules/@expressivecss/expressive/dist/js/')) modules.add(basename(path));
      else sources.add(path);
    }
  }
  return { files, inputs: new Set(inputPaths.values()), modules, sources };
}
